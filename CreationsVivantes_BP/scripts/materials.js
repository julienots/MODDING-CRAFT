const cache = new Map();
const get = (n) => MAT["minecraft:" + n] ?? (ALIAS["minecraft:" + n] ? MAT[ALIAS["minecraft:" + n]] : undefined);

function guess(id) {
  let n = id.includes(":") ? id.split(":")[1] : id;
  n = n.replace(/^(waxed_|infested_|lit_|unlit_|powered_|unpowered_)/, "").replace(/^element_\d+$/, "iron_block");
  let r = get(n);
  if (r) return r;
  // escaliers, dalles, murs, barrières... -> le bloc de base
  const base = n.replace(SUFFIX, "");
  if (base !== n) {
    for (const c of [base, base + "s", base + "_planks", base + "_block", base.replace(/_brick$/, "_bricks")]) { r = get(c); if (r) return r; }
  }
  if (/_ore$/.test(n)) { r = get(n.replace(/^deepslate_/, "")); if (r) return r; }
  if (n.startsWith("stripped_")) { r = get(n.slice(9)) ?? get(n.slice(9).replace(/_wood$|_hyphae$/, "_log")); if (r) return r; }
  // couleurs
  const col = COLORS.find((c) => n.startsWith(c + "_") || n.includes("_" + c + "_"));
  if (col) {
    const c = col === "silver" ? "light_gray" : col;
    const fam = n.includes("glazed") ? "_glazed_terracotta" : n.includes("powder") ? "_concrete_powder" : n.includes("glass") ? "_stained_glass"
      : n.includes("terracotta") || n.includes("hardened_clay") ? "_terracotta" : n.includes("concrete") ? "_concrete" : "_wool";
    r = get(c + fam) ?? get(c + "_wool");
    if (r) return r;
  }
  // bois
  const wd = WOODS.find((w) => n.includes(w));
  if (wd) {
    const w = wd === "pale_oak" ? "birch" : wd;
    if (/leaves/.test(n)) r = get(w + "_leaves") ?? get("oak_leaves");
    else if (/(_log|_wood|_stem|_hyphae)$/.test(n)) r = get(w + "_log") ?? get(w + "_stem") ?? get("oak_log");
    else r = get(w + "_planks");
    if (r) return r;
  }
  for (const [k, ref] of KEYWORDS) if (n.includes(k)) { r = get(ref); if (r) return r; }
  return MAT["minecraft:stone"];
}

// Fonctionne avec TOUS les blocs (vanilla ou d'autres add-ons) : [texture, solidité, pouvoir]
export function matOf(id) {
  if (!id) return MAT["minecraft:stone"];
  let r = MAT[id];
  if (r) return r;
  r = cache.get(id);
  if (!r) { r = guess(id); cache.set(id, r); }
  return r;
}
